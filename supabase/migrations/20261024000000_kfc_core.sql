create or replace function private.is_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select coalesce((select exists (
    select 1 from public.users u
    where u.auth_user_id = (select auth.uid())
      and u.status = 'approved' and u.role = 'admin'
  )), false)
$$;

create or replace function private.is_approved_member()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select coalesce((select exists (
    select 1 from public.users u
    where u.auth_user_id = (select auth.uid()) and u.status = 'approved'
  )), false)
$$;

create or replace function private.can_access_group(target_group_id bigint)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select coalesce((select exists (
    select 1
    from public.groups g
    where g.id = target_group_id and g.active
      and (
        exists (
          select 1 from public.users u
          where u.auth_user_id = (select auth.uid())
            and u.status = 'approved' and u.role = 'admin'
        )
        or exists (
          select 1 from public.group_members gm
          join public.users u on u.id = gm.user_id
          where gm.group_id = g.id and u.auth_user_id = (select auth.uid())
            and u.status = 'approved'
        )
      )
  )), false)
$$;

