create table public.notice_popups (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 160),
  content text not null check (length(trim(content)) between 1 and 5000),
  link_type text not null default 'none' check (link_type in ('none','web','poll','announcement','event')),
  link_url text,
  target_id bigint,
  active boolean not null default true,
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((link_type = 'none' and link_url is null and target_id is null)
    or (link_type = 'web' and link_url ~ '^https://[^[:space:]]+$' and target_id is null)
    or (link_type in ('poll','announcement','event') and target_id is not null and link_url is null))
);

create index notice_popups_active_created_idx on public.notice_popups (active, created_at desc);
alter table public.notice_popups enable row level security;
revoke all on public.notice_popups from public, anon, authenticated;
grant select, insert, update, delete on public.notice_popups to service_role;
grant usage, select on sequence public.notice_popups_id_seq to service_role;
