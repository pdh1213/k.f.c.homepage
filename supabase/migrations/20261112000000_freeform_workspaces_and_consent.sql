create or replace function private.can_access_freeform(target_board_id bigint)
returns boolean language sql stable security definer set search_path=''
as $$ select coalesce((select exists(
  select 1 from public.freeform_boards b join public.users u on u.auth_user_id=(select auth.uid())
  where b.id=target_board_id and u.status='approved'
    and (u.role='admin' or b.owner_id=u.id or u.id=any(b.member_ids))
)),false) $$;
revoke all on function private.can_access_freeform(bigint) from public,anon;
grant execute on function private.can_access_freeform(bigint) to authenticated;

