create policy kfc_freeform_images_read on storage.objects for select to authenticated using (
  bucket_id='freeform-images' and case when (storage.foldername(name))[1]='freeform'
  and (storage.foldername(name))[2] ~ '^[0-9]+$'
  then (select private.can_access_freeform((storage.foldername(name))[2]::bigint)) else false end
);
create policy kfc_freeform_images_upload on storage.objects for insert to authenticated with check (
  bucket_id='freeform-images' and (storage.foldername(name))[1]='freeform'
  and (storage.foldername(name))[3]=(select private.current_profile_id())::text
  and case when (storage.foldername(name))[2] ~ '^[0-9]+$'
    then (select private.can_access_freeform((storage.foldername(name))[2]::bigint)) else false end
);

drop policy if exists kfc_group_broadcast_receive on realtime.messages;
create policy kfc_group_broadcast_receive on realtime.messages for select to authenticated using (
  (topic='kfc-executive' and (select private.is_officer()))
  or case
    when topic ~ '^kfc-group:[0-9]+$' then (select private.can_access_group(split_part(topic,':',2)::bigint))
    when topic ~ '^kfc-direct:[0-9]+$' then (select private.can_access_direct_chat(split_part(topic,':',2)::bigint))
    when topic ~ '^kfc-freeform:[0-9]+$' then (select private.can_access_freeform(split_part(topic,':',2)::bigint))
    else false end
);
