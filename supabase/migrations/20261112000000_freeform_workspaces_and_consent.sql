-- Project planning, collaborative boards, and explicit site-use acknowledgement.
alter table public.users add column if not exists site_use_consented_at timestamptz;

create table public.freeform_boards (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  owner_id bigint not null references public.users(id) on delete cascade,
  member_ids bigint[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index freeform_boards_owner_idx on public.freeform_boards(owner_id);
create index freeform_boards_members_idx on public.freeform_boards using gin(member_ids);
create table public.freeform_items (
  id bigint generated by default as identity primary key,
  board_id bigint not null references public.freeform_boards(id) on delete cascade,
  item_type text not null check (item_type in ('note','link','shape','image')),
  content text not null default '' check (char_length(content) <= 4000),
  x integer not null default 80 check (x between 0 and 5000),
  y integer not null default 80 check (y between 0 and 5000),
  color text not null default 'cream' check (color in ('cream','blue','pink','green')),
  created_by bigint not null references public.users(id) on delete cascade,
  updated_at timestamptz not null default now()
);
create index freeform_items_board_idx on public.freeform_items(board_id,id);

create table public.project_workspaces (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  kind text not null check (kind in ('robot','webapp')),
  phase text not null default 'in_progress' check (phase in ('in_progress','completed')),
  collaborator_ids bigint[] not null default '{}',
  board_id bigint references public.freeform_boards(id) on delete set null,
  group_id bigint references public.groups(id) on delete set null,
  showroom_project_id bigint references public.showroom_projects(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index project_workspaces_owner_idx on public.project_workspaces(owner_id);
create index project_workspaces_collaborators_idx on public.project_workspaces using gin(collaborator_ids);

create table public.admin_chat_view_audit (
  id bigint generated by default as identity primary key,
  admin_id bigint not null references public.users(id) on delete cascade,
  chat_kind text not null check (chat_kind in ('direct','group')),
  chat_id bigint not null,
  viewed_at timestamptz not null default now()
);
create index admin_chat_view_audit_viewed_idx on public.admin_chat_view_audit(viewed_at desc);

alter table public.freeform_boards enable row level security;
