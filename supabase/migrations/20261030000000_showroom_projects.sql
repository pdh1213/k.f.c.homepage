-- K.F.C. 3.0 public showroom. All writes go through kfc-api after role checks.
create table if not exists public.showroom_projects (
  id bigint generated by default as identity primary key,
  owner_id bigint references public.users(id) on delete cascade,
  kind text not null check (kind in ('robot', 'webapp')),
  name text not null check (char_length(name) between 1 and 120),
  description text not null check (char_length(description) between 1 and 2000),
  instructions text not null default '',
  web_url text,
  image_path text not null unique,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  rejection_reason text not null default '',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by bigint references public.users(id) on delete set null,
  check ((kind = 'robot' and web_url is null and instructions = '') or (kind = 'webapp' and web_url is not null and char_length(instructions) > 0))
);
create index if not exists showroom_projects_status_created_idx on public.showroom_projects(status, created_at desc);
create index if not exists showroom_projects_owner_created_idx on public.showroom_projects(owner_id, created_at desc);
alter table public.showroom_projects enable row level security;
revoke all on public.showroom_projects from anon, authenticated;

create table if not exists public.showroom_competitions (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  year smallint not null check (year between 2000 and 2100),
  result text not null default '',
  description text not null default '',
  published boolean not null default true,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists showroom_competitions_published_year_idx on public.showroom_competitions(published, year desc);
alter table public.showroom_competitions enable row level security;
revoke all on public.showroom_competitions from anon, authenticated;

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('project-images', 'project-images', false, 10485760,
  array['image/jpeg','image/png','image/webp','image/gif','image/avif'])
on conflict(id) do update set public=false, file_size_limit=excluded.file_size_limit,
  allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists kfc_project_images_upload on storage.objects;
create policy kfc_project_images_upload on storage.objects for insert to authenticated with check (
  bucket_id = 'project-images'
  and (storage.foldername(name))[1] = 'projects'
  and (storage.foldername(name))[2] = (select private.current_profile_id())::text
  and (select private.is_approved_member())
);
drop policy if exists kfc_project_images_owner_read on storage.objects;
create policy kfc_project_images_owner_read on storage.objects for select to authenticated using (
  bucket_id = 'project-images'
  and (storage.foldername(name))[1] = 'projects'
  and (storage.foldername(name))[2] = (select private.current_profile_id())::text
  and (select private.is_approved_member())
);


