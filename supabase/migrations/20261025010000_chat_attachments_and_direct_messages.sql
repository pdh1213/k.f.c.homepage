create table if not exists public.direct_chats (
  id bigint generated by default as identity primary key,
  member_low_id bigint not null references public.users(id) on delete cascade,
  member_high_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (member_low_id < member_high_id),
  unique(member_low_id, member_high_id)
);
create table if not exists public.direct_chat_members (
  chat_id bigint not null references public.direct_chats(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(chat_id,user_id)
);
create index if not exists direct_chat_members_user_idx on public.direct_chat_members(user_id,chat_id);
create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null references public.direct_chats(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  content text not null default '' check (length(content) <= 2000),
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments)='array'),
  reply_to_id bigint references public.direct_messages(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists direct_messages_chat_id_idx on public.direct_messages(chat_id,id desc);
create table if not exists public.chat_reactions (
  id bigint generated by default as identity primary key,
  group_message_id bigint references public.messages(id) on delete cascade,
  direct_message_id bigint references public.direct_messages(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  emoji text not null check (emoji in ('👍','❤️','😂','😮','👏','🚀')),
  created_at timestamptz not null default now(),
  check ((group_message_id is not null)::int + (direct_message_id is not null)::int = 1)
);
create unique index if not exists chat_reaction_group_unique on public.chat_reactions(group_message_id,user_id,emoji) where group_message_id is not null;
create unique index if not exists chat_reaction_direct_unique on public.chat_reactions(direct_message_id,user_id,emoji) where direct_message_id is not null;

