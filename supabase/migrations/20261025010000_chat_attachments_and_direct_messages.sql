create or replace function private.current_profile_id()
returns bigint language sql stable security definer set search_path=''
as $$ select id from public.users where auth_user_id=(select auth.uid()) and status='approved' limit 1 $$;
create or replace function private.can_access_direct_chat(target_chat_id bigint)
returns boolean language sql stable security definer set search_path=''
as $$ select coalesce((select exists(select 1 from public.direct_chat_members dcm join public.users u on u.id=dcm.user_id where dcm.chat_id=target_chat_id and u.auth_user_id=(select auth.uid()) and u.status='approved')),false) $$;
revoke all on function private.current_profile_id() from public,anon;
revoke all on function private.can_access_direct_chat(bigint) from public,anon;
grant execute on function private.current_profile_id() to authenticated;
grant execute on function private.can_access_direct_chat(bigint) to authenticated;

