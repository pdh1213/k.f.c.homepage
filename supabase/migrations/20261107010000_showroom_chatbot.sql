create table if not exists public.showroom_chatbot_faqs (
  id bigint generated by default as identity primary key,
  question text not null check (char_length(question) between 1 and 180),
  answer text not null check (char_length(answer) between 1 and 3000),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.showroom_chatbot_faqs enable row level security;
revoke all on public.showroom_chatbot_faqs from anon, authenticated;

create table if not exists public.showroom_chatbot_questions (
  id bigint generated by default as identity primary key,
  ticket uuid not null unique default gen_random_uuid(),
  question text not null check (char_length(question) between 1 and 500),
  answer text not null default '',
  status text not null default 'pending' check (status in ('pending','answered')),
  created_at timestamptz not null default now(),
  answered_at timestamptz
);
create index if not exists showroom_chatbot_questions_status_idx on public.showroom_chatbot_questions(status,created_at desc);
alter table public.showroom_chatbot_questions enable row level security;
revoke all on public.showroom_chatbot_questions from anon, authenticated;

